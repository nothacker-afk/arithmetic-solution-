def supported_locales():
    return sorted(TRANSLATIONS.keys())


def get_strings(locale):
    strings = dict(TRANSLATIONS.get(DEFAULT_LOCALE, {}))
    if locale in TRANSLATIONS:
        strings.update(TRANSLATIONS[locale])
    return strings


def pick_locale(accept_language):
    if not accept_language:
        return DEFAULT_LOCALE
    for token in accept_language.split(","):
        base = token.strip().split(";")[0].strip().lower().split("-")[0]
        if base in TRANSLATIONS:
            return base
    return DEFAULT_LOCALE
